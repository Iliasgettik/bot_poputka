_STRONG_RE, _STRONG_PLAIN = _compile(STRONG)
_AMBIG_RE, _ = _compile(AMBIGUOUS)
_NON_RE, _ = _compile(NON_TALAS)
_BISHKEK_RE, _ = _compile(BISHKEK)


# ---------------------------------------------------------------------------
# Публичные функции
# ---------------------------------------------------------------------------
def _fuzzy(place_norm: str) -> bool:
    s = place_norm.replace(" ", "")
    if len(s) < 5:
        return False
    for stem in _STRONG_PLAIN:
        if len(stem) < 6:
            continue
        if SequenceMatcher(None, s[: len(stem) + 1], stem).ratio() >= 0.86:
            return True
    return False


def is_talas_place(place) -> bool:
    """Однозначно таласское место (с поиском опечаток)."""
    if not place:
        return False
    n = _norm(place)
    if _hit(n, _STRONG_RE):
        return True
    if _hit(n, _NON_RE):
        return False
    return _fuzzy(n)


def is_ambiguous_place(place) -> bool:
    return bool(place) and _hit(_norm(place), _AMBIG_RE) and not is_talas_place(place)


def is_known_non_talas(place) -> bool:
    return bool(place) and _hit(_norm(place), _NON_RE) and not is_talas_place(place)


def is_bishkek(place) -> bool:
    return bool(place) and _hit(_norm(place), _BISHKEK_RE)


def is_talas_route(origin, destination):
    """
    True  — хотя бы один конец в Таласской области;
    False — оба (все указанные) конца точно вне Таласа;
    None  — не удалось определить (неизвестное село).
    """
    ends = [e for e in (origin, destination) if e]
    if not ends:
        return None

    if any(is_talas_place(e) for e in ends):
        return True

    # спорное название: считаем таласским, если второй конец — Бишкек/пусто/неизвестный
    for i, e in enumerate(ends):
        if is_ambiguous_place(e):
            others = ends[:i] + ends[i + 1:]
            if not others or all(is_bishkek(o) or not is_known_non_talas(o) for o in others):
                return True

    if all(is_known_non_talas(e) for e in ends):
        return False
    return None


def decide_not_talas(origin, destination, gpt_talas_route) -> bool:
    """True = объявление НЕ про Талас, публиковать нельзя."""
    verdict = is_talas_route(origin, destination)
    if verdict is True:
        return False
    if verdict is False:
        return True
    # verdict is None → неизвестное село
    if gpt_talas_route is True:
        return False
    return STRICT_UNKNOWN and gpt_talas_route is False


