_STRONG_RE, _STRONG_PLAIN = _compile(STRONG)
_AMBIG_RE, _ = _compile(AMBIGUOUS)
_NON_RE, _ = _compile(NON_TALAS)
_BISHKEK_RE, _ = _compile(BISHKEK)


# ---------------------------------------------------------------------------
# Публичные функции
# ---------------------------------------------------------------------------
def _fuzzy(place_norm: str) -> bool:
    s = place_norm.replace(" ", "")
    if len(s) < 5:
        return False
    for stem in _STRONG_PLAIN:
        if len(stem) < 6:
            continue
        if SequenceMatcher(None, s[: len(stem) + 1], stem).ratio() >= 0.86:
            return True
    return False


def is_talas_place(place) -> bool:
    """Однозначно таласское место (с поиском опечаток)."""
    if not place:
        return False
    n = _norm(place)
    if _hit(n, _STRONG_RE):
        return True
    if _hit(n, _NON_RE):
        return False
    return _fuzzy(n)


def is_ambiguous_place(place) -> bool:
    return bool(place) and _hit(_norm(place), _AMBIG_RE) and not is_talas_place(place)


def is_bishkek(place) -> bool:
    return bool(place) and _hit(_norm(place), _BISHKEK_RE)


def is_talas_route(origin, destination) -> bool:
    """True только если хотя бы один конец — известное таласское место."""
    ends = [e for e in (origin, destination) if e]
    if not ends:
        return False

    if any(is_talas_place(e) for e in ends):
        return True

    # спорное название: пропускаем, только если второй конец Бишкек (или его нет)
    if AMBIGUOUS_OK:
        for i, e in enumerate(ends):
            if is_ambiguous_place(e):
                others = ends[:i] + ends[i + 1:]
                if not others or any(is_bishkek(o) for o in others):
                    return True
    return False


def decide_not_talas(origin, destination, gpt_talas_route=None) -> bool:
    """True = объявление НЕ про Талас, публиковать нельзя. Ответ GPT не учитывается."""
    return not is_talas_route(origin, destination)


