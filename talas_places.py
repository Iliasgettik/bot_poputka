# ---------------------------------------------------------------------------
# Нормализация
# ---------------------------------------------------------------------------
_FOLD = str.maketrans({
    "ө": "о", "ү": "у", "ң": "н", "ё": "е", "ы": "и", "ъ": "", "ь": "",
    "ӧ": "о", "ҥ": "н", "ӱ": "у",
})
_LAT_DIGRAPHS = (("dzh", "ж"), ("sh", "ш"), ("ch", "ч"), ("zh", "ж"), ("kh", "х"),
                 ("yu", "ю"), ("ya", "я"), ("yo", "е"), ("ts", "ц"))
_LAT = {
    "a": "а", "b": "б", "c": "к", "d": "д", "e": "е", "f": "ф", "g": "г", "h": "х",
    "i": "и", "j": "ж", "k": "к", "l": "л", "m": "м", "n": "н", "o": "о", "p": "п",
    "q": "к", "r": "р", "s": "с", "t": "т", "u": "у", "v": "в", "w": "в", "x": "кс",
    "y": "и", "z": "з", "ö": "о", "ü": "у", "ñ": "н", "ŋ": "н", "ı": "и",
}


def _translit(s: str) -> str:
    if re.search(r"[а-яөүңё]", s):          # уже кириллица — не трогаем
        return s
    for a, b in _LAT_DIGRAPHS:
        s = s.replace(a, b)
    return "".join(_LAT.get(ch, ch) for ch in s)


def _norm(s) -> str:
    s = str(s or "").lower()
    s = _translit(s).translate(_FOLD)
    s = re.sub(r"[\-–—_.,/()«»\"']", " ", s)
    s = re.sub(r"[^\w\s]", " ", s)
    s = re.sub(r"(.)\1+", r"\1", s)          # аа→а, лл→л
    return re.sub(r"\s+", " ", s).strip()


def _compile(stems):
    """stems: строки; «|» разделяет варианты написания одного и того же места."""
    out, plain = [], []
    for item in stems:
        for variant in item.split("|"):
            n = _norm(variant)
            if not n:
                continue
            words = n.split(" ")
            out.append(re.compile(r"(?<![а-яa-z0-9])" + r"\s*".join(map(re.escape, words))))
            plain.append(n.replace(" ", ""))
    return out, plain


def _hit(place_norm: str, compiled) -> bool:
    return any(p.search(place_norm) for p in compiled)


